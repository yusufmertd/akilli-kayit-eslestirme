// "Ad|KIS1,KIS2" satırlarını [{ name, abbr: [] }] listesine çevirir
export function parseList(text) {
  return text.trim().split('\n').map((line) => {
    const [name, abbr = ''] = line.split('|');
    return { name: name.trim(), abbr: abbr.split(',').map((a) => a.trim()).filter(Boolean) };
  });
}

